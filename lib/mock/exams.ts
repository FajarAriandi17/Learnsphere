export function examById(id: string) {
  return examPackages.find((exam) => exam.id === id);
}

/**
 * The context a saved package was generated with. Stored packages will carry
 * their own snapshot once `exams` is a real table; until then it is rebuilt from
 * the summary so the detail page can render the same items every time.
 */
export function contextFor(exam: ExamSummary): GenerationContext {
  return {
    level: "SMP",
    grade: exam.grade,
    className: exam.className,
    subject: exam.subject,
    curriculum: curricula[0].name,
    academicYear: activePeriod.academicYear,
    semester: activePeriod.semester,
    topic: exam.topic,
    count: exam.questionCount,
    types: exam.types,
    difficulty: exam.difficulty,
  };
}

